  function ensureButton() {
    let button = document.getElementById("languageToggle");
    if (!button) {
      button = document.createElement("button");
      button.id = "languageToggle";
      button.type = "button";
      button.className = "language-toggle language-toggle-floating";
      button.textContent = "हिंदी";
      button.setAttribute("aria-label", "Switch to Hindi");
      document.body.appendChild(button);
    }
    return button;
  }

  function translateText(lang) {
    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
      acceptNode(node) {
        if (!node.data.trim() || node.parentElement?.closest("script, style, noscript, #languageToggle")) {
          return NodeFilter.FILTER_REJECT;
        }
        return NodeFilter.FILTER_ACCEPT;
      }
    });
    let node;
    while ((node = walker.nextNode())) {
      if (!originals.has(node)) originals.set(node, node.data);
      const original = originals.get(node);
      if (lang === "en") {
        node.data = original;
        continue;
      }
      const key = normalise(original);
      if (translations[key]) {
        const leading = original.match(/^\s*/)?.[0] || "";
        const trailing = original.match(/\s*$/)?.[0] || "";
        node.data = leading + translations[key] + trailing;
      }
    }
  }

  function applyLanguage(lang) {
    lang = lang === "hi" ? "hi" : "en";
    document.documentElement.lang = lang;
    translateText(lang);
    const button = ensureButton();
    button.textContent = lang === "en" ? "हिंदी" : "English";
    button.setAttribute("aria-label", lang === "en" ? "हिंदी में बदलें" : "Switch to English");
    button.setAttribute("title", lang === "en" ? "Switch to Hindi" : "Switch to English");
    const fileName = location.pathname.split("/").pop() || "index.html";
    if (document.querySelector("title") && pageTitles[fileName]) {
      document.title = pageTitles[fileName][lang];
    }
    try { localStorage.setItem("ranaLanguage", lang); } catch (_) {}
  }

  const start = () => {
    const button = ensureButton();
    let saved = "en";
    try { saved = localStorage.getItem("ranaLanguage") || "en"; } catch (_) {}
    applyLanguage(saved);
    button.addEventListener("click", () => {
      applyLanguage(document.documentElement.lang === "en" ? "hi" : "en");
    });
  };

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", start, { once: true });
  } else {
    start();
  }
